// Question 1: Using break Statement
console.log("Using Break Statement:");

for (let i = 1; i <= 10; i++) {

    if (i === 5) {
        break;
    }

    console.log(i);
}

// Question 2: Using continue Statement
console.log("Using Continue Statement:");

for (let i = 1; i <= 10; i++) {

    if (i === 5) {
        continue;
    }

    console.log(i);
}
