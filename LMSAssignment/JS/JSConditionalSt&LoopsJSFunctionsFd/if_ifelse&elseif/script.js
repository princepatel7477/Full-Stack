// Question 1: Using if and if...else Statements

let age = 20;

if (age >= 18) {
    console.log("Person is an adult.");
}

let marks = 65;

if (marks >= 33) {
    console.log("Student has passed.");
} else {
    console.log("Student has failed.");
}

let number = 15;

if (number % 2 === 0) {
    console.log("Number is even.");
} else {
    console.log("Number is odd.");
}

let studentMarks = 85;

if (studentMarks >= 90) {
    console.log("Grade A");
} else if (studentMarks >= 75) {
    console.log("Grade B");
} else if (studentMarks >= 50) {
    console.log("Grade C");
} else {
    console.log("Fail");
}
